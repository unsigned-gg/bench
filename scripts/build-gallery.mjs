import { readFileSync, writeFileSync, mkdirSync, cpSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";
import { build } from "esbuild";
import { writeArrayBuffer } from "geotiff";
import { validateInventory } from "./gallery-contract.mjs";
const root = fileURLToPath(new URL("../", import.meta.url));
export async function buildGallery(
  out = join(root, "cerebral/visualizations"),
) {
  const src = join(root, "cerebral-src/visualizations"),
    inventory = JSON.parse(readFileSync(join(src, "inventory.json"), "utf8"));
  validateInventory(inventory);
  const result = spawnSync(
    "cargo",
    [
      "build",
      "--manifest-path",
      join(root, "visualization-wasm/Cargo.toml"),
      "--locked",
      "--target",
      "wasm32-unknown-unknown",
      "--release",
    ],
    {
      stdio: "inherit",
      env: {
        ...process.env,
        CARGO_ENCODED_RUSTFLAGS: [
          ...(process.env.CARGO_ENCODED_RUSTFLAGS?.split("\x1f") || []),
          `--remap-path-prefix=${process.env.HOME || root}=/build`,
        ].join("\x1f"),
      },
    },
  );
  if (result.status !== 0) throw Error("WASM compilation failed");
  mkdirSync(out, { recursive: true });
  const escape = (s) =>
    String(s).replace(
      /[&<>"']/g,
      (c) =>
        ({
          "&": "&amp;",
          "<": "&lt;",
          ">": "&gt;",
          '"': "&quot;",
          "'": "&#39;",
        })[c],
    );
  const categories = [...new Set(inventory.entries.map((e) => e.category))];
  const catalog = inventory.entries
    .map(
      (e) =>
        `<a href="?chart=${escape(e.id)}" data-example="${escape(e.id)}"><small>${String(e.index).padStart(3, "0")}</small><span>${escape(e.title)}</span></a>`,
    )
    .join("\n");
  const html = readFileSync(join(src, "index.html"), "utf8")
    .replace(
      "{{CATEGORY_OPTIONS}}",
      categories
        .map(
          (c) =>
            `<option value="${c}">${c[0].toUpperCase() + c.slice(1)} / ${inventory.entries.filter((e) => e.category === c).length}</option>`,
        )
        .join(""),
    )
    .replace("{{CATALOG}}", catalog);
  writeFileSync(join(out, "index.html"), html);
  for (const f of ["lab.css", "inventory.json"])
    cpSync(join(src, f), join(out, f));
  cpSync(
    join(
      root,
      "visualization-wasm/target/wasm32-unknown-unknown/release/cerebral_visualization_kernels.wasm",
    ),
    join(out, "kernels.wasm"),
  );
  const terrain = Array.from({ length: 64 * 64 }, (_, i) => {
    const x = ((i % 64) - 32) / 64,
      y = (Math.floor(i / 64) - 32) / 64;
    return Math.round(
      20 +
        180 * Math.exp(-(x * x + y * y) * 12) +
        20 * Math.sin(x * 24) * Math.cos(y * 18),
    );
  });
  const raster = await writeArrayBuffer(terrain, {
    width: 64,
    height: 64,
    BitsPerSample: [8],
    SampleFormat: [1],
    GeographicTypeGeoKey: 4326,
    ModelPixelScale: [0.01, 0.01, 0],
    ModelTiepoint: [0, 0, 0, 11, 46, 0],
  });
  writeFileSync(join(out, "terrain.tiff"), new Uint8Array(raster));
  const bundle = await build({
    entryPoints: [join(src, "lab.js")],
    bundle: true,
    format: "esm",
    target: ["es2022"],
    minify: true,
    outfile: join(out, "lab.js"),
    legalComments: "eof",
    metafile: true,
  });
  const packages = [
    ...new Set(
      Object.keys(bundle.metafile.inputs).flatMap((file) => {
        const match = file.match(/node_modules\/((?:@[^/]+\/)?[^/]+)/);
        return match ? [match[1]] : [];
      }),
    ),
  ].sort();
  let notice =
    "Cerebral visualization lab\n\n174 original implementations of concepts indexed in the D3 gallery.\nSource inventory: https://observablehq.com/@d3/gallery @1120\nAuthor attribution and original notebook links: inventory.json\nGallery metadata: Copyright Mike Bostock / Observable; ISC.\nNo source notebook body or historical dataset is redistributed.\nDemo values are synthetic, generated by local Rust/WASM kernels.\nNatural Earth geographic source data is public domain; atlas packaging notices follow.\n\n";
  for (const name of packages) {
    const base = join(root, "node_modules", name);
    let license = "";
    for (const f of [
      "LICENSE",
      "LICENSE.md",
      "LICENSE.txt",
      "license",
      "license.md",
      "LICENSE-MIT",
      "COPYING",
    ]) {
      try {
        license = readFileSync(join(base, f), "utf8");
        break;
      } catch {}
    }
    if (!license && name === "lerc")
      license =
        "Copyright 2015–2021 Esri\n" +
        readFileSync(join(root, "third-party/LICENSE-LERC.txt"), "utf8");
    if (!license) throw Error(`Missing bundled license: ${name}`);
    notice += `\n--- ${name} ---\n${license}\n`;
  }
  writeFileSync(join(out, "NOTICE.txt"), notice);
  console.log(
    "Built visualization lab: 174 entries, Three.js bundle, compiled WASM, source inventory and attribution",
  );
}
if (process.argv[1] === fileURLToPath(import.meta.url)) await buildGallery();
